"""Write the gradient-field figure (Figure 3) as TikZ: outputs/figures/tikz/grad_flow.tex plus three magnitude images.

Same fields as grad_flow.py: plain gradients with respect to the child's encoder output v, the tangent
vector of the paper's background section, with y = expm_0(v), with
the training weights (0.1 for the cone and ARGENT, 0.5 for Gromov), the inter-modal constants, and the parent of Figure 1 (c = 0.1,
d(x, 0) = 0.6, saturated: the cone is a half-space). Everything is vector TikZ in the paper's colours
and fonts except the smooth magnitude backgrounds, written as PNGs.
Style follows Figure 1 (cone_disk.py, gromov_disk.py): the view cropped to a dashed circle, with x at
TOP_FRAC of its radius; the ramp of each loss family; zero sets hatched (cone) or drawn as the black ray beyond x
(ARGENT, Gromov); origin and parent as rootfill / markfill points.
Layout (single column): the cropped disk with the window, and the window itself; then one row per loss,
gradient direction (left) and magnitude (right). The angular losses share a log scale (ANG_RANGE),
whose tip marks the divergence at the parent; the Gromov loss has its own linear scale.
Rows are named by the loss, each at its inter-modal constant: the entailment loss at eta = 0.7 (HyCoCLIP, PHyCLIP),
the adaptive loss of ARGENT at h = 1, and the Gromov loss at k = 2.
"""
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LogNorm, Normalize

import style
from grad_flow import PHI, PARENT_DIST, N_MAG, KEYS, lift, to_disk, from_disk, grads, window
import grad_flow
grad_flow.HALF = 0.08    # tight window: the 1/d growth of the angular gradients then spans the panel

PAPER = style.OUT
OUT_TEX = PAPER / "tikz" / "grad_flow.tex"
OUT_IMG = PAPER / "grad_flow"
OUT_IMG.mkdir(parents=True, exist_ok=True)
OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
TOP_FRAC = 0.4          # x at this fraction of the top-left crop radius, as VIEW_FRAC in Figure 1 (cone_disk.py)
ANG_RANGE = (1e0, 1e2)   # log scale of the angular losses; their gradient diverges at the parent
N_ARROW = 10
S = 2.75            # panel side (cm)
GAP = 0.22          # gap between the two panels of a row (cm)
ROW = S + 0.22      # row pitch (cm)
CB_W = 0.22         # colourbar width (cm)
# Rows are named by the loss, as in Figure 1; the methods that use each go in the caption
# (entailment: MERU, HyCoCLIP, PHyCLIP; adaptive: ARGENT). One colour for every row.
# Rows in the notation of Figure 1 and the background section: the entailment loss (eq. ent), the adaptive
# loss of ARGENT (eq. ada) and the Gromov loss, each with its argument.
LABELS = {"cone": ("\\textbf{(a)} $\\lent$, $\\eta = 0.7$", "labeltext"), "argent": ("\\textbf{(b)} $\\lada$, $h = 1$", "labeltext"),
          "gromov": ("\\textbf{(c)} $\\lGromov$, $k = 2$", "labeltext")}
# Ramps of Figure 1 (style.py): REST for the baselines' angular losses, GROMOV for the Gromov loss.
FAMILY = {"cone": "rest", "argent": "rest", "gromov": "gromov"}
STOPS = {"rest": [c.lstrip("#") for c in style.REST_STOPS], "gromov": [c.lstrip("#") for c in style.GROMOV_STOPS]}
CMAPS = {"rest": style.REST_CMAP, "gromov": style.GROMOV_CMAP}


def f(v):
    return f"{v:.3f}"


def path(points):
    return " -- ".join(f"({f(a)},{f(b)})" for a, b in points)


def nice_ticks(vmax):
    step = next(s for s in (0.05, 0.1, 0.2, 0.5, 1, 2, 5, 10) if vmax / s <= 4.5)
    return [round(i * step, 10) for i in range(int(vmax / step + 1e-9) + 1)]


def main():
    vx = PARENT_DIST * np.array([np.cos(PHI), np.sin(PHI)])
    xp = to_disk(vx)
    x = lift(vx)
    xb = (x[0][None, None], np.array(x[1])[None, None])
    gx, gy, p, w = window(xp, N_MAG)
    base, g = grads(xb, from_disk(p))
    # Arrows at cell centres, shifted slightly off the ray through x, where the angular gradients
    # have no direction.
    cell = 2 * w / N_ARROW
    cen = np.arange(N_ARROW) * cell - w + cell / 2
    pa = np.stack(np.meshgrid(xp[0] + cen, xp[1] + cen + 0.12 * cell), axis=-1)
    va = from_disk(pa)
    _, ga = grads(xb, va)
    mags = {k: np.linalg.norm(g[k], axis=-1) for k in KEYS}
    gromov_max = float(np.nanmax(mags["gromov"]))
    norms = {"cone": LogNorm(*ANG_RANGE), "argent": LogNorm(*ANG_RANGE), "gromov": Normalize(0, gromov_max)}

    # Window coordinates -> panel coordinates (cm), origin at the panel's lower-left corner.
    x0, y0 = gx.min(), gy.min()
    sx, sy = S / (gx.max() - x0), S / (gy.max() - y0)
    to_panel = lambda q: ((q[..., 0] - x0) * sx, (q[..., 1] - y0) * sy)
    px, py = to_panel(xp)
    ray = np.array([np.cos(PHI), np.sin(PHI)])
    far = to_panel(xp + 2 * w * ray)          # beyond the frame; clipped

    OUT_IMG.mkdir(exist_ok=True)
    fig, scratch = plt.subplots()             # only used to trace the dead-zone outline
    tex = ["% Generated by figures/grad_flow_tikz.py; edit there, not here.",
           "% Gradient of each hierarchy term on a child around a fixed parent x (plain gradients with respect",
           "% to the encoder output). Rows: entailment cone, ARGENT, Gromov; left: direction, right: magnitude.",
           "\\begin{tikzpicture}[",
           "    frame/.style={draw=nodestroke, line width=0.5pt},",
           "    zeroray/.style={draw=labeltext, line width=0.8pt},",
           "    pt/.style={circle, draw=nodestroke, line width=0.5pt, minimum size=1.5mm, inner sep=0pt},",
           "    lab/.style={font=\\scriptsize, text=labeltext, inner sep=0.5pt},",
           "    head/.style={font=\\footnotesize, text=labeltext},",
           "  ]"]
    for fam, stops in STOPS.items():
        for i, c in enumerate(stops):
            tex.append(f"\\definecolor{{{fam}{i}}}{{HTML}}{{{c}}}")

    XLAB = {"left": "anchor=south east, xshift=-0.4mm, yshift=0.9mm",
            "dead": "anchor=south west, xshift=0.9mm, yshift=0.9mm, fill=rest0, inner sep=0.8pt"}

    def xlabel(cx_, cy_, where="left"):
        return f"\\node[lab, {XLAB[where]}] at ({f(cx_)},{f(cy_)}) {{$\\boldsymbol{{x}}$}};"

    def parent(cx_, cy_, where="left"):
        return [f"\\node[pt, fill=markfill] at ({f(cx_)},{f(cy_)}) {{}};", xlabel(cx_, cy_, where)]

    # Top row: the disk cropped to a dashed circle with x at TOP_FRAC of its radius, with the window
    # (left); the window itself (right). x sits where it does in Figure 1; the window is small at this
    # scale, and x is marked by the box alone, not by a dot.
    top = 3 * ROW + 0.5
    R = 1.1                                   # radius of the cropped disk (cm)
    k = R * TOP_FRAC / np.linalg.norm(xp)     # cm per unit of the Poincare disk
    cx, cy = S / 2, top + S / 2               # the disk centred on the direction column, level with the window
    bx, by, bs = cx + k * (xp[0] - w), cy + k * (xp[1] - w), 2 * k * w
    zx = S + GAP                              # the zoomed window: a panel of the magnitude column
    tex += [f"\\draw[draw=nodestroke, line width=0.5pt, dash pattern=on 2pt off 1.4pt] ({f(cx)},{f(cy)}) circle ({f(R)});",
            f"\\draw[nodestroke, line width=0.3pt] ({f(bx + bs)},{f(by + bs)}) -- ({f(zx)},{f(top + S)});",
            f"\\draw[nodestroke, line width=0.3pt] ({f(bx + bs)},{f(by)}) -- ({f(zx)},{f(top)});",
            f"\\node[pt, fill=rootfill, minimum size=1.0mm, line width=0.4pt] at ({f(cx)},{f(cy)}) {{}};",
            f"\\node[lab, anchor=north east, xshift=0.1mm, yshift=0.1mm] at ({f(cx)},{f(cy)}) {{$\\mathbf{{0}}$}};",
            f"\\draw[frame, line width=0.4pt] ({f(bx)},{f(by)}) rectangle ++({f(bs)},{f(bs)});",
            f"\\node[lab, anchor=south east, xshift=-0.2mm, yshift=0.2mm] at ({f(bx)},{f(by + bs)}) {{$\\boldsymbol{{x}}$}};",
            f"\\draw[frame] ({f(zx)},{f(top)}) rectangle ({f(zx + S)},{f(top + S)});"]
    tex += parent(zx + px, top + py)

    for i, key in enumerate(KEYS):
        oy = (2 - i) * ROW
        dead = (base[key] <= 1e-12) if key == "cone" else np.zeros_like(base[key], dtype=bool)  # only the cone has a region
        label, col = LABELS[key]
        tex.append(f"% ---- {key}")
        tex.append(f"\\node[head, rotate=90, text={col}, anchor=south, align=center] at (-0.08,{f(oy + S / 2)}) {{{label}}};")

        # Zero set, as in Figure 1: the cone's half-space hatched over the lightest ramp colour; for the
        # angle and the Gromov loss, the ray beyond x.
        zero = []
        if dead.any():
            cs = scratch.contourf(gx, gy, dead.astype(float), levels=[0.5, 1.5])
            for seg in cs.allsegs[0]:
                qx, qy = to_panel(seg)
                poly = path(zip(qx[::4], qy[::4]))
                zero += [f"  \\begin{{scope}}\\clip {poly} -- cycle;",
                         f"    \\fill[{FAMILY[key]}0] (0,0) rectangle ({f(S)},{f(S)});",
                         f"    \\foreach \\t in {{-{f(S)},-{f(S - 0.16)},...,{f(S)}}} {{\\draw[nodestroke, line width=0.25pt] (\\t,0) -- ++({f(S)},{f(S)});}}",
                         "  \\end{scope}",
                         f"  \\draw[nodestroke, line width=0.5pt] {poly};"]
        else:
            zero.append(f"  \\draw[zeroray] ({f(px)},{f(py)}) -- ({f(far[0])},{f(far[1])});")

        # Direction panel.
        tex.append(f"\\begin{{scope}}[shift={{(0,{f(oy)})}}]")
        tex.append(f"  \\clip (0,0) rectangle ({f(S)},{f(S)});")
        tex += zero
        step = to_disk(va - 1e-4 * ga[key]) - pa
        sn = np.linalg.norm(step, axis=-1)
        ux, uy = to_panel(pa)
        # No arrow on x or under its label (above left of x).
        lx, ly = (px + 0.22, py + 0.2) if key == "cone" else (px - 0.22, py + 0.2)
        live = (sn > 1e-13) & (np.linalg.norm(pa - xp, axis=-1) > 0.5 * cell) \
            & (np.hypot(ux - lx, uy - ly) > 0.75 * S / N_ARROW)
        half = 0.28 * S / N_ARROW
        for a in range(N_ARROW):
            for b in range(N_ARROW):
                if not live[a, b]:
                    continue
                d = step[a, b] / sn[a, b]
                tex.append(f"  \\draw[-stealth, {col}, line width=0.38pt] ({f(ux[a, b] - half * d[0])},{f(uy[a, b] - half * d[1])})"
                           f" -- ({f(ux[a, b] + half * d[0])},{f(uy[a, b] + half * d[1])});")
        tex.append("\\end{scope}")
        tex.append(f"\\draw[frame] (0,{f(oy)}) rectangle ({f(S)},{f(oy + S)});")
        where = "dead" if key == "cone" else "left"   # in the cone row, x is labelled inside the dead zone
        tex += parent(px, oy + py, where)

        # Magnitude panel: image background, zero set on top.
        m = np.where(dead, np.nan, mags[key])
        rgba = CMAPS[FAMILY[key]](norms[key](m))
        rgba[np.isnan(m)] = matplotlib.colors.to_rgba("#" + STOPS[FAMILY[key]][0])
        plt.imsave(OUT_IMG / f"{key}.png", rgba[::-1])
        ox = S + GAP
        tex.append(f"\\begin{{scope}}[shift={{({f(ox)},{f(oy)})}}]")
        tex.append(f"  \\node[anchor=south west, inner sep=0pt] at (0,0) {{\\includegraphics[width={f(S)}cm,height={f(S)}cm]{{figures/grad_flow/{key}.png}}}};")
        tex.append(f"  \\clip (0,0) rectangle ({f(S)},{f(S)});")
        tex += zero
        tex.append("\\end{scope}")
        tex.append(f"\\draw[frame] ({f(ox)},{f(oy)}) rectangle ({f(ox + S)},{f(oy + S)});")
        # Hollow here, so the parent does not cover the core of the magnitude field.
        tex += [f"\\node[pt] at ({f(ox + px)},{f(oy + py)}) {{}};", xlabel(ox + px, oy + py, where)]

    tex.append(f"\\node[head, anchor=base] at ({f(S / 2)},{f(3 * ROW - 0.08)}) {{Direction}};")
    tex.append(f"\\node[head, anchor=base] at ({f(S + GAP + S / 2)},{f(3 * ROW - 0.08)}) "
               "{Magnitude $\\|\\nabla_{\\boldsymbol{v}}\\,\\ell\\|$};")

    # Colourbars: the angular scale beside the first two rows (its tip marks the divergence), Gromov beside
    # the last; the quantity is named in the column head.
    cbx = 2 * S + GAP + 0.18

    def colourbar(y_lo, y_hi, pos, ticks, tip, fam):
        """pos: value -> fraction of the bar; ticks: (value, label)."""
        out = []
        h = (y_hi - y_lo) / 3
        for j in range(3):
            out.append(f"\\shade[bottom color={fam}{j}, top color={fam}{j + 1}] ({f(cbx)},{f(y_lo + j * h)}) rectangle ++({f(CB_W)},{f(h)});")
        out.append(f"\\draw[draw=nodestroke, line width=0.3pt] ({f(cbx)},{f(y_lo)}) rectangle ({f(cbx + CB_W)},{f(y_hi)});")
        if tip:
            out.append(f"\\fill[{fam}3] ({f(cbx)},{f(y_hi)}) -- ({f(cbx + CB_W / 2)},{f(y_hi + 0.22)}) -- ({f(cbx + CB_W)},{f(y_hi)}) -- cycle;")
            out.append(f"\\node[lab, font=\\small, anchor=south] at ({f(cbx + CB_W / 2)},{f(y_hi + 0.22)}) {{$\\infty$}};")  # the clip: diverges at x
        for t, lab in ticks:
            ty = y_lo + (y_hi - y_lo) * pos(t)
            out.append(f"\\draw[draw=nodestroke, line width=0.3pt] ({f(cbx + CB_W)},{f(ty)}) -- ++(0.06,0) node[lab, right=0.2mm] {{{lab}}};")
        return out

    lo, hi = np.log10(ANG_RANGE)
    tex += colourbar(ROW, 2 * ROW + S - 0.25, lambda t: (np.log10(t) - lo) / (hi - lo),
                     [(1, "1"), (10, "10"), (100, "100")], tip=True, fam="rest")
    tex += colourbar(0.0, S, lambda t: t / gromov_max, [(t, f"{t:g}") for t in nice_ticks(gromov_max)], tip=False, fam="gromov")
    tex.append("\\end{tikzpicture}")
    plt.close(fig)
    OUT_TEX.write_text("\n".join(tex) + "\n")
    print(f"wrote {OUT_TEX}; Gromov max {gromov_max:.3f}")


if __name__ == "__main__":
    main()
