"""Write the eight text trees out as TikZ (text width, two columns of four trees).

With a noun as argument, write that tree alone, with the columns fitted to its own texts so that it fits one column
at scriptsize, and without the header row that names the levels:

    python figures/text_trees_tikz.py            # outputs/figures/tikz/text_trees.tex
    python figures/text_trees_tikz.py boat       # outputs/figures/tikz/text_tree_boat.tex

Every tree is drawn left to right, one column per level: the category (1), two subcategories (2), two phrases with
attributes per subcategory (3) and three scenes per phrase (4). A scene repeats the phrase to its left and adds the
words shown after the dots. Marks are those of the plane figures (tree_plot.branch_style): the first branch red
circles, the second blue triangles, light at level 2 and strong at level 4, the root grey.

Source: assets/qualitative/text_trees.json (--trees for another file).
"""
import json
import sys

from matplotlib.font_manager import FontProperties
from matplotlib.textpath import TextPath

import style
from tree_plot import branch_style

OUT = style.OUT / "tikz" / "text_trees.tex"
LEVELS = ["category", "subcategory", "attributes", "scene"]
# Geometry in cm, at \scriptsize. X: left edge of each level's badge; END: where that level's labels end at the latest.
X = [0.0, 1.42, 3.92, 7.22]
END = [1.02, 3.52, 6.82, 10.4]
ROW, GROUP, BRANCH, TREE, HEAD = 0.275, 0.07, 0.13, 0.34, 0.50   # row pitch and extra gaps between phrases, branches, trees
COL_GAP, CURVE, TEXT_DX = 0.55, 0.20, 0.21
TREES_PER_COLUMN = 4


def strip(text):
    return text[3:] if text.startswith("an ") else text[2:] if text.startswith("a ") else text


def tex(text):
    return text.replace("&", r"\&").replace("%", r"\%")


def fitted_columns(tree):
    """Column positions for one tree, from the widths of its own labels at \\scriptsize (7 pt Times), in cm."""
    font = FontProperties(family=["Times New Roman", "Times"], size=7)
    cm = lambda text: 1.03 * TextPath((0, 0), text, prop=font).get_extents().width / 72 * 2.54
    xs, ends, x = [], [], 0.0
    for level, name in enumerate(LEVELS):
        labels = [("\u2026 " + n["tail"]) if n["level"] == 4 else strip(n["text"]) for n in tree["nodes"] if n["level"] == level + 1]
        widest = max(cm(t) + (0.06 if level == 3 else 0.0) for t in labels)      # no header row in the single tree
        xs.append(x)
        ends.append(x + TEXT_DX + widest + 0.07)
        x = ends[-1] + 0.31
    ends[-1] -= 0.07
    return xs, ends


def layout(tree, y_top):
    """Row (y) of every node: leaves top to bottom, a parent at the middle of its children. Returns ys and the bottom."""
    nodes = tree["nodes"]
    children = {j: [k for k, n in enumerate(nodes) if n["parent"] == j] for j in range(len(nodes))}
    ys, y = {}, y_top

    def place(j):
        nonlocal y
        if not children[j]:
            ys[j] = y
            y -= ROW
            return
        for i, k in enumerate(children[j]):
            if i:
                y -= {1: BRANCH, 2: GROUP}.get(nodes[j]["level"], 0.0)
            place(k)
        ys[j] = (ys[children[j][0]] + ys[children[j][-1]]) / 2

    place(0)
    return ys, y


def main():
    global X, END, OUT
    path = next((sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == "--trees"), "assets/qualitative/text_trees.json")
    trees = json.load(open(style.REPO / path))["trees"]
    index = list(range(len(trees)))                                # a tree keeps its colour across figures
    args = [a for i, a in enumerate(sys.argv[1:], 1) if not a.startswith("--") and sys.argv[i - 1] != "--trees"]
    noun = args[0] if args else None
    if noun:
        index = [[t["noun"] for t in trees].index(noun)]
        X, END = fitted_columns(trees[index[0]])
        OUT = OUT.with_name(f"text_tree_{noun}.tex")
    lines = ["% Generated by figures/text_trees_tikz.py.",
             rf"\definecolor{{nodestroke}}{{HTML}}{{{style.NODE_STROKE[1:]}}}",
             rf"\definecolor{{labeltext}}{{HTML}}{{{style.LABEL_TEXT[1:]}}}"]
    shades = sorted({c for n in index for c in branch_style(trees[n])[2]})
    name = {c: f"tt{c[1:]}" for c in shades}
    lines += [rf"\definecolor{{{name[c]}}}{{HTML}}{{{c[1:]}}}" for c in shades]
    lines += [r"\begin{tikzpicture}[",
              r"    dot/.style={circle, inner sep=0pt, minimum size=2.1mm, draw=white, line width=0.3pt},",
              r"    lab/.style={font=\scriptsize, text=labeltext, inner sep=0pt, anchor=west},",
              r"    edge/.style={line width=0.75pt, line cap=round},",
              r"  ]"]
    width = END[-1]
    for column in range((len(index) + TREES_PER_COLUMN - 1) // TREES_PER_COLUMN):
        x0 = column * (width + COL_GAP)
        y = 0.0                                                    # no header row: the caption names the levels
        for n in index[column * TREES_PER_COLUMN:(column + 1) * TREES_PER_COLUMN]:
            tree = trees[n]
            nodes = tree["nodes"]
            ys, bottom = layout(tree, y)
            _, branch, shade, mark = branch_style(tree)
            colour = [name[c] for c in shade]
            lines.append(f"  % {tree['noun']}")
            for j, node in enumerate(nodes):                       # edges first, under the nodes
                if node["parent"] is None:
                    continue
                p, lp = node["parent"], nodes[node["parent"]]["level"] - 1
                xa, xb = x0 + END[lp], x0 + X[node["level"] - 1] - 0.125
                lines.append(rf"  \draw[edge, {colour[j]}] ({xa:.3f}, {ys[p]:.3f}) .. controls +({CURVE}, 0) and +(-{CURVE}, 0) .. ({xb:.3f}, {ys[j]:.3f});")
            for j, node in enumerate(nodes):
                level = node["level"] - 1
                text = r"\ldots\ " + tex(node["tail"]) if node["level"] == 4 else tex(strip(node["text"]))
                has_children = any(m["parent"] == j for m in nodes)
                x = x0 + X[level]
                if has_children:                                   # a stem from the label to where the branches leave
                    lines.append(rf"  \node[lab] (t) at ({x + TEXT_DX:.3f}, {ys[j]:.3f}) {{{text}}};")
                    lines.append(rf"  \draw[edge, {colour[j]}] ([xshift=1.6pt]t.east) -- ({x0 + END[level]:.3f}, {ys[j]:.3f});")
                else:
                    lines.append(rf"  \node[lab] at ({x + TEXT_DX:.3f}, {ys[j]:.3f}) {{{text}}};")
                if mark[j][0] == "^":                              # triangle, same height as the dot
                    r = 0.135
                    lines.append(rf"  \filldraw[fill={colour[j]}, draw=white, line width=0.3pt, line join=round] ({x:.3f}, {ys[j] + r:.3f}) -- "
                                 rf"({x - 0.866 * r:.3f}, {ys[j] - 0.5 * r:.3f}) -- ({x + 0.866 * r:.3f}, {ys[j] - 0.5 * r:.3f}) -- cycle;")
                else:
                    lines.append(rf"  \node[dot, fill={colour[j]}] at ({x:.3f}, {ys[j]:.3f}) {{}};")
            y = bottom - TREE
    lines.append(r"\end{tikzpicture}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    columns = (len(index) + TREES_PER_COLUMN - 1) // TREES_PER_COLUMN
    print(f"wrote {OUT} ({len(lines)} lines); natural width {columns * width + (columns - 1) * COL_GAP:.2f} cm, height {-y - TREE:.2f} cm")


if __name__ == "__main__":
    main()
